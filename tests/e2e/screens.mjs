// Gera capturas de tela para a documentação (docs/img).
import path from 'node:path';
import { launch, root } from './launch.mjs';

const out = path.join(root, 'docs', 'img');
const { app, page } = await launch();
const ef = (fn, ...args) => page.evaluate(([f, a]) => window.__ef[f](...a), [fn, args]);
const cell = async (a1, shift = false) => {
  await ef('cellRect', a1);
  await page.waitForTimeout(50);
  const r = await ef('cellRect', a1);
  if (shift) await page.keyboard.down('Shift');
  await page.mouse.click(r.x + Math.min(20, r.w / 2), r.y + r.h / 2);
  if (shift) await page.keyboard.up('Shift');
};
const shot = (name) => page.screenshot({ path: path.join(out, name + '.png') });

await shot('01-inicio');
await page.click('[data-testid="tpl-gastos"]');
await page.waitForSelector('[data-testid="editor"]');
await page.waitForTimeout(300);
await shot('02-modelo-gastos');
await cell('D3');
await cell('D7', true);
await page.click('[data-testid="tab-calculos"]');
await shot('03-guia-calculos');
await page.click('[data-testid="calc-sum"]');
await page.waitForSelector('[data-testid="quick-panel"]');
await page.waitForTimeout(400);
await shot('04-somar-selecao');
await page.keyboard.press('Escape');
await cell('B3');
await page.keyboard.type('=SO');
await page.waitForTimeout(200);
await shot('05-autocompletar');
await page.keyboard.press('Escape');
await page.keyboard.press('Escape');
await page.click('[data-testid="btn-help"]');
await page.click('[data-testid="help-cores"]');
await page.click('[data-testid="help-show"]');
await page.waitForTimeout(300);
await shot('06-ajuda');
await page.click('[data-testid="btn-help"]');
await page.click('[data-testid="btn-file"]');
await page.waitForTimeout(200);
await shot('07-menu-arquivo');
await page.click('[data-testid="fm-print"]');
await page.waitForSelector('[data-testid="print-panel"]');
await page.waitForTimeout(400);
await shot('08-imprimir');
await page.keyboard.press('Escape');
await cell('G2');
await cell('H7', true);
await page.click('[data-testid="tab-inserir"]');
await page.click('[data-testid="btn-chart"]');
await page.waitForSelector('[data-testid="chart-panel"]');
await page.waitForTimeout(200);
await shot('09-grafico');
